/**
 * Raw dataset (JSON files) → SQL inserts for the content tables.
 * Deterministic: the same files always give the same SQL. Runs inside one
 * transaction so a partial import is impossible.
 */
import { DEFAULT_SPECIES_ID, NOTE_KEYS, doiFromUrl, type RawDataset } from "./rawDataset";

type Value = string | number | boolean | null | undefined | { json: unknown } | { textArray: string[] };

function lit(v: Value): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`Non-finite number ${v}`);
    return String(v);
  }
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "string") return `'${v.replace(/'/g, "''")}'`;
  if ("json" in v) return `${lit(JSON.stringify(v.json))}::jsonb`;
  return `array[${v.textArray.map((s) => lit(s)).join(", ")}]::text[]`;
}

function insert(table: string, rows: Record<string, Value>[]): string {
  if (rows.length === 0) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values};\n\n`;
}

const links = <K extends string>(ownerCol: K, ownerId: string, col: string, ids: string[]) =>
  ids.map((id, position) => ({ [ownerCol]: ownerId, [col]: id, position }) as Record<string, Value>);

export function toSeedSql(raw: RawDataset): string {
  let sql = "-- Generated by scripts/db/generate-seed.ts from src/data/*.json. Do not edit by hand.\nbegin;\n\n";

  sql += insert("dataset_notes", [
    { key: NOTE_KEYS.species, body: raw.species.note },
    { key: NOTE_KEYS.migrations, body: raw.migrations.disclaimer },
    { key: NOTE_KEYS.populations, body: raw.populations.note },
    { key: NOTE_KEYS.milestones, body: raw.milestones.note },
    { key: NOTE_KEYS.sources, body: raw.sources.note },
  ]);

  const sourceRows = [
    ...raw.migrations.sources.map((s, i) => ({ s, i, file: "migrations" })),
    ...raw.sources.sources.map((s, i) => ({ s, i, file: "sources" })),
  ].map(({ s, i, file }) => {
    const doi = doiFromUrl(s.url);
    return {
      id: s.id,
      sort_order: i,
      legacy_file: file,
      citation: s.citation,
      url: s.url ?? null,
      doi,
      publication_year: Number(s.citation.match(/\((\d{4})\)/)?.[1]) || null,
    };
  });
  sql += insert("sources", sourceRows);

  sql += insert(
    "species",
    raw.species.species.map((s, i) => ({
      id: s.id,
      sort_order: i,
      name: s.name,
      scientific_name: s.scientificName,
      genus: s.genus,
      species_group: s.group,
      classification: s.classification,
      taxonomy_note: s.taxonomyNote,
      older_bp: s.timeRange.older,
      younger_bp: s.timeRange.younger,
      time_note: s.timeNote,
      distribution: s.distribution,
      physical: s.physical,
      technology: s.technology,
      relationships: s.relationships,
      confidence: s.confidence,
      camera: { json: s.camera },
      focus_year: s.focusYear,
    })),
  );
  sql += insert("species_sources", raw.species.species.flatMap((s) => links("species_id", s.id, "source_id", s.sources)));

  const sites = raw.events.sites;
  sql += insert(
    "archaeological_sites",
    sites.map((s, i) => ({
      id: s.id,
      sort_order: i,
      name: s.name,
      region: s.region,
      lat: s.location.lat,
      lng: s.location.lng,
      older_bp: s.dateRange[0],
      younger_bp: s.dateRange[1],
      description: s.description,
      details: s.details ?? null,
      confidence: s.confidence,
    })),
  );
  // A site without speciesIds is Homo sapiens (loader default); [] means maker unknown.
  sql += insert("site_species", sites.flatMap((s) => links("site_id", s.id, "species_id", s.speciesIds ?? [DEFAULT_SPECIES_ID])));
  sql += insert("site_sources", sites.flatMap((s) => links("site_id", s.id, "source_id", s.sources)));
  sql += insert("species_sites", raw.species.species.flatMap((s) => links("species_id", s.id, "site_id", s.siteIds)));

  sql += insert(
    "historical_periods",
    raw.events.periods.map((p, i) => ({
      id: p.id,
      sort_order: i,
      name: p.name,
      short_name: p.shortName ?? null,
      start_bp: p.startYear,
      end_bp: p.endYear,
      description: p.description,
      confidence: p.confidence,
    })),
  );

  const routes = raw.migrations.routes;
  sql += insert(
    "migration_routes",
    routes.map((r, i) => ({
      id: r.id,
      sort_order: i,
      species_id: r.speciesId ?? DEFAULT_SPECIES_ID,
      name: r.name,
      category: r.category,
      path: { json: r.path },
      branches: r.branches ? { json: r.branches } : null,
      particle_config: { json: r.particleConfig },
      confidence: r.confidence,
      data_status: r.dataStatus,
      uncertainty: r.uncertainty,
      origin: r.origin,
      destination: r.destination,
      intermediate_regions: { textArray: r.intermediateRegions },
      path_description: r.pathDescription,
      description: r.description,
      people: r.people,
      historical_context: r.historicalContext,
      significance: r.significance,
      camera: { json: r.camera },
    })),
  );
  // Evidence ids are derived from route id + position so the seed stays deterministic.
  const evidenceId = (routeId: string, position: number) =>
    `(select id from public.route_evidence where route_id = ${lit(routeId)} and position = ${position})`;
  sql += insert(
    "route_evidence",
    routes.flatMap((r) => r.evidence.map((e, position) => ({ route_id: r.id, position, type: e.type, description: e.description }))),
  );
  const evSources = routes.flatMap((r) =>
    r.evidence.flatMap((e, p) => (e.sourceIds ?? []).map((sourceId, position) => ({ ev: evidenceId(r.id, p), sourceId, position }))),
  );
  if (evSources.length) {
    sql += `insert into public.route_evidence_sources (evidence_id, source_id, position) values\n${evSources
      .map((x) => `  (${x.ev}, ${lit(x.sourceId)}, ${x.position})`)
      .join(",\n")};\n\n`;
  }
  sql += insert("route_sites", routes.flatMap((r) => links("route_id", r.id, "site_id", r.siteIds)));

  const clusters = raw.populations.clusters;
  sql += insert(
    "population_clusters",
    clusters.map((c, i) => ({
      id: c.id,
      sort_order: i,
      species_id: c.speciesId,
      region: c.region,
      lat: c.coordinates.lat,
      lng: c.coordinates.lng,
      lobes: { json: c.lobes },
      start_bp: c.startYear,
      established_bp: c.establishedYear,
      end_bp: c.endYear ?? null,
      fade_years: c.fadeYears ?? null,
      growth_origin: c.growthOrigin ? { json: c.growthOrigin } : null,
      color_from: c.colorFrom,
      visual_density: c.visualDensity,
      confidence: c.confidence,
      attested_bp: c.attestedYear ?? null,
      basis_note: c.basisNote,
      land_only: c.landOnly ?? null,
    })),
  );
  sql += insert("cluster_routes", clusters.flatMap((c) => links("cluster_id", c.id, "route_id", c.relatedRouteIds)));
  sql += insert("cluster_sites", clusters.flatMap((c) => links("cluster_id", c.id, "site_id", c.siteIds)));

  const ms = raw.milestones.milestones;
  sql += insert(
    "milestones",
    ms.map((m, i) => ({
      id: m.id,
      sort_order: i,
      title: m.title,
      category: m.category,
      approximate_start_bp: m.approximateStartYear,
      approximate_end_bp: m.approximateEndYear ?? null,
      date_label: m.dateLabel,
      lat: m.geographicLocation.lat,
      lng: m.geographicLocation.lng,
      location_label: m.geographicLocation.label,
      location_approximate: m.geographicLocation.approximate ?? null,
      short_description: m.shortDescription,
      detailed_description: m.detailedDescription,
      evidence: m.evidence,
      origin_note: m.originNote,
      significance: m.significance,
      evidence_type: m.evidenceType,
      confidence: m.confidence,
      visual_icon: m.visualIcon,
      animation_type: m.animationType,
    })),
  );
  sql += insert("milestone_species", ms.flatMap((m) => links("milestone_id", m.id, "species_id", m.relatedSpeciesIds)));
  sql += insert("milestone_routes", ms.flatMap((m) => links("milestone_id", m.id, "route_id", m.relatedRouteIds ?? [])));
  sql += insert("milestone_sites", ms.flatMap((m) => links("milestone_id", m.id, "site_id", m.relatedSiteIds ?? [])));
  sql += insert("milestone_sources", ms.flatMap((m) => links("milestone_id", m.id, "source_id", m.sources)));

  return sql + "commit;\n";
}
